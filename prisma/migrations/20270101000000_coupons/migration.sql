-- Phase 4 — coupons and redemptions.
--
-- Discounts are applied before GST (tax is charged on the discounted
-- subtotal), so `Order.total`/`taxAmount` are already net of `discountAmount`.
-- A redemption is created with the pending order and released only if that
-- order is cancelled before payment; paid orders keep theirs forever.

-- CreateEnum
